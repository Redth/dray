#!/usr/bin/env node
// Copies Tabulator into wwwroot, for the same reason as Monaco and xterm: the app must work with
// the network unplugged, and a strict WebView CSP would block a CDN anyway.
//
// Two files. The ESM build, because everything else Dray loads is an ES module, and the base
// stylesheet — not one of Tabulator's themes. The themes paint a grid that looks like a web page's
// table; DataGrid.razor.css restyles it from Dray's tokens so it reads as the same control as the
// rest of the app in either appearance.
//
//   node build/vendor-tabulator.mjs           refresh wwwroot/lib/tabulator from node_modules
//   node build/vendor-tabulator.mjs --check   fail if the vendored copy is stale (CI gate)

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'Dray.Ui', 'wwwroot', 'lib', 'tabulator');
const manifestPath = join(target, 'vendored.json');

const check = process.argv.includes('--check');

// The grid and its base stylesheet. Sorting, column resizing, auto-fit sizing and row
// virtualization are each a piece of table behaviour that looks simple and is not — resizing alone
// has to survive a window resize, a column being hidden, and content wider than its column.
const FILES = [
  { from: ['tabulator-tables', 'dist', 'js', 'tabulator_esm.min.mjs'], to: 'tabulator.mjs' },
  { from: ['tabulator-tables', 'dist', 'css', 'tabulator.min.css'], to: 'tabulator.css' },
];

const LICENCES = [
  { from: ['tabulator-tables', 'LICENSE'], to: 'LICENSE' },
];

function pkgPath(...parts) {
  return join(root, 'node_modules', ...parts);
}

function version() {
  return JSON.parse(readFileSync(pkgPath('tabulator-tables', 'package.json'), 'utf8')).version;
}

function hashOf(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 16);
}

if (!existsSync(pkgPath('tabulator-tables'))) {
  console.error('tabulator-tables is not installed. Run `npm install` first.');
  process.exit(1);
}

const manifest = {
  note: 'Generated by build/vendor-tabulator.mjs. Do not edit, and do not edit the files it lists.',
  version: version(),
  files: Object.fromEntries(FILES.map(f => [f.to, hashOf(pkgPath(...f.from))])),
};

if (check) {
  const problems = [];

  if (!existsSync(manifestPath)) {
    problems.push('wwwroot/lib/tabulator has never been vendored.');
  } else {
    const current = JSON.parse(readFileSync(manifestPath, 'utf8'));

    if (current.version !== manifest.version) {
      problems.push(`vendored Tabulator is ${current.version}, package.json wants ${manifest.version}.`);
    }

    for (const [file, hash] of Object.entries(manifest.files)) {
      const path = join(target, file);

      if (!existsSync(path)) problems.push(`missing: ${file}`);
      else if (hashOf(path) !== hash) problems.push(`modified: ${file}`);
    }
  }

  if (problems.length > 0) {
    console.error('\x1b[31m\x1b[1m✗ Vendored Tabulator is stale\x1b[0m\n');
    for (const problem of problems) console.error(`  ${problem}`);
    console.error('\n  Run: npm run vendor:tabulator');
    process.exit(1);
  }

  console.log(`\x1b[32m\x1b[1m✓ Tabulator ${manifest.version} vendored and current\x1b[0m`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

for (const file of [...FILES, ...LICENCES]) {
  cpSync(pkgPath(...file.from), join(target, file.to));
}

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const bytes = FILES.reduce((sum, f) => sum + statSync(join(target, f.to)).size, 0);

console.log(`\x1b[32m\x1b[1m✓ Vendored Tabulator ${manifest.version}\x1b[0m`);
console.log(`  ${FILES.length} files, ${(bytes / 1024).toFixed(0)} KB → wwwroot/lib/tabulator`);
