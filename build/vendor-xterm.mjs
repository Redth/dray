#!/usr/bin/env node
// Copies xterm.js into wwwroot, for the same reason as Monaco: the app must work offline.
//
// Four files, not a package. xterm ships its sources and maps alongside the built bundle, and none
// of that is useful to someone running Dray — the maps alone are larger than the code.
//
//   node build/vendor-xterm.mjs           refresh wwwroot/lib/xterm from node_modules
//   node build/vendor-xterm.mjs --check   fail if the vendored copy is stale (CI gate)

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'Dray.Ui', 'wwwroot', 'lib', 'xterm');
const manifestPath = join(target, 'vendored.json');

const check = process.argv.includes('--check');

// The core, its stylesheet, and the addons Dray actually loads.
//
// The addons are xterm's own and are the reason not to hand-roll any of this: sizing to the
// element, GPU rendering, correct widths for emoji and CJK, clickable URLs and find-in-scrollback
// are each a subtle piece of terminal behaviour that looks simple and is not.
const FILES = [
  { from: ['@xterm/xterm', 'lib', 'xterm.js'], to: 'xterm.js' },
  { from: ['@xterm/xterm', 'css', 'xterm.css'], to: 'xterm.css' },

  // Measures the host element and reports the column/row count the remote pty needs.
  { from: ['@xterm/addon-fit', 'lib', 'addon-fit.js'], to: 'addon-fit.js' },

  // GPU rendering, with the canvas renderer as the fallback where WebGL is refused — which
  // includes some WebView configurations, so both ship.
  { from: ['@xterm/addon-webgl', 'lib', 'addon-webgl.js'], to: 'addon-webgl.js' },
  { from: ['@xterm/addon-canvas', 'lib', 'addon-canvas.js'], to: 'addon-canvas.js' },

  // A container's logs are full of URLs; making them clickable costs one addon.
  { from: ['@xterm/addon-web-links', 'lib', 'addon-web-links.js'], to: 'addon-web-links.js' },

  // Find in scrollback. A shell session is something people search.
  { from: ['@xterm/addon-search', 'lib', 'addon-search.js'], to: 'addon-search.js' },

  // Unicode 11 widths. Without it, emoji and CJK are measured as one cell and every line after
  // one of them is drawn shifted.
  { from: ['@xterm/addon-unicode11', 'lib', 'addon-unicode11.js'], to: 'addon-unicode11.js' },

  // OSC 52, so a program inside the container can put something on the user's clipboard.
  { from: ['@xterm/addon-clipboard', 'lib', 'addon-clipboard.js'], to: 'addon-clipboard.js' },
];

const LICENCES = [
  { from: ['@xterm/xterm', 'LICENSE'], to: 'LICENSE' },
];

function pkgPath(...parts) {
  return join(root, 'node_modules', ...parts);
}

function version() {
  return JSON.parse(readFileSync(pkgPath('@xterm', 'xterm', 'package.json'), 'utf8')).version;
}

function hashOf(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 16);
}

if (!existsSync(pkgPath('@xterm', 'xterm'))) {
  console.error('@xterm/xterm is not installed. Run `npm install` first.');
  process.exit(1);
}

const manifest = {
  note: 'Generated by build/vendor-xterm.mjs. Do not edit, and do not edit the files it lists.',
  version: version(),
  files: Object.fromEntries(FILES.map(f => [f.to, hashOf(pkgPath(...f.from))])),
};

if (check) {
  const problems = [];

  if (!existsSync(manifestPath)) {
    problems.push('wwwroot/lib/xterm has never been vendored.');
  } else {
    const current = JSON.parse(readFileSync(manifestPath, 'utf8'));

    if (current.version !== manifest.version) {
      problems.push(`vendored xterm is ${current.version}, package.json wants ${manifest.version}.`);
    }

    for (const [file, hash] of Object.entries(manifest.files)) {
      const path = join(target, file);

      if (!existsSync(path)) problems.push(`missing: ${file}`);
      else if (hashOf(path) !== hash) problems.push(`modified: ${file}`);
    }
  }

  if (problems.length > 0) {
    console.error('\x1b[31m\x1b[1m✗ Vendored xterm is stale\x1b[0m\n');
    for (const problem of problems) console.error(`  ${problem}`);
    console.error('\n  Run: npm run vendor:xterm');
    process.exit(1);
  }

  console.log(`\x1b[32m\x1b[1m✓ xterm ${manifest.version} vendored and current\x1b[0m`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

for (const file of [...FILES, ...LICENCES]) {
  cpSync(pkgPath(...file.from), join(target, file.to));
}

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const bytes = FILES.reduce((sum, f) => sum + statSync(join(target, f.to)).size, 0);

console.log(`\x1b[32m\x1b[1m✓ Vendored xterm ${manifest.version}\x1b[0m`);
console.log(`  ${FILES.length} files, ${(bytes / 1024).toFixed(0)} KB → wwwroot/lib/xterm`);
