#!/usr/bin/env node
// Generates the icon layer from design/icons.json:
//
//   src/Dray.Core/Shell/Icons.g.cs         IconRef enum + per-platform resolution tables
//   src/Dray.Ui/wwwroot/icons/sprite.svg   the vendored sprite the WebView references
//
// docs/NATIVE-SHELL.md section 2.3: shared code names an IconRef and each platform resolves it.
// A missing mapping is a build error, never a blank button on Linux.
//
//   node build/gen-icons.mjs           write
//   node build/gen-icons.mjs --check   fail if stale (CI)

import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { repoRoot } from './color.mjs';

const check = process.argv.includes('--check');
const src = JSON.parse(readFileSync(join(repoRoot, 'design', 'icons.json'), 'utf8'));
const { geometry, icons } = src;
const BANNER = 'Generated by build/gen-icons.mjs from design/icons.json. Do not edit.';

// Every icon must define all three mappings — this is the check that replaces Sherpa's
// hand-maintained, silently-incomplete translation dictionary.
const missing = [];
for (const [name, def] of Object.entries(icons)) {
  for (const key of ['sf', 'gtk', 'svg']) {
    if (!def[key] || !def[key].trim()) missing.push(`${name}.${key}`);
  }
}
if (missing.length) {
  console.error(`\x1b[31mIncomplete icon mappings:\x1b[0m ${missing.join(', ')}`);
  process.exit(1);
}

const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const names = Object.keys(icons);

// ------------------------------------------------------------------ sprite.svg

const symbols = names
  .map((n) => `  <symbol id="i-${n}" viewBox="${geometry.viewBox}">${icons[n].svg}</symbol>`)
  .join('\n');

const spriteBody = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true"
     fill="none" stroke="currentColor" stroke-width="${geometry.strokeWidth}"
     stroke-linecap="${geometry.linecap}" stroke-linejoin="${geometry.linejoin}">
${symbols}
</svg>`;

const sprite = `<!-- ${BANNER} -->
${spriteBody}
`;

// ------------------------------------------------------------------ IconSprite.razor
//
// The same symbols as a component, mounted once per document.
//
// WebKit does not resolve <use href="file.svg#id"> — an external reference renders a 0x0 box and
// no error, which is every icon in the macOS app silently disappearing. Chrome and Firefox do
// resolve it, so the web head looked fine and the bug lived only where nobody could see it.
// Inlining the symbols makes every <use> a same-document reference, which every engine supports.
//
// A component rather than markup pasted into each host page: there are three of those (the dev
// host, the macOS window, the macOS dialog) and a fourth is one head away.

const spriteRazor = `@* ${BANNER} *@

@* Mounted once per document — see build/gen-icons.mjs for why these are inline rather than
   referenced from icons/sprite.svg. The file is still generated: the native heads and anything
   outside the app read it. *@

${spriteBody}
`;

// ------------------------------------------------------------------ Icons.g.cs

const table = (key) =>
  names.map((n) => `        [IconRef.${pascal(n)}] = ${JSON.stringify(icons[n][key])},`).join('\n');

const cs = `// ${BANNER}
#nullable enable

namespace Dray.Core.Shell;

/// <summary>
/// Every icon Dray can render. Shared code names one of these; each platform head resolves it to
/// its own vocabulary. Never put an SF Symbol string in shared code.
/// </summary>
public enum IconRef
{
${names.map((n) => `    ${pascal(n)},`).join('\n')}
}

/// <summary>Resolves an <see cref="IconRef"/> for a specific platform's chrome.</summary>
public static class Icons
{
    /// <summary>SF Symbol name, for AppKit chrome.</summary>
    public static string SfSymbol(IconRef icon) => SfSymbols[icon];

    /// <summary>Adwaita icon name, for GTK chrome.</summary>
    public static string GtkName(IconRef icon) => GtkNames[icon];

    /// <summary>
    /// Sprite fragment id for the WebView (and for Windows chrome, which renders the same
    /// geometry rather than guessing at Segoe Fluent codepoints).
    /// </summary>
    public static string SpriteId(IconRef icon) => "i-" + SpriteSlugs[icon];

    public static readonly IReadOnlyDictionary<IconRef, string> SfSymbols = new Dictionary<IconRef, string>
    {
${table('sf')}
    };

    public static readonly IReadOnlyDictionary<IconRef, string> GtkNames = new Dictionary<IconRef, string>
    {
${table('gtk')}
    };

    internal static readonly IReadOnlyDictionary<IconRef, string> SpriteSlugs = new Dictionary<IconRef, string>
    {
${names.map((n) => `        [IconRef.${pascal(n)}] = ${JSON.stringify(n)},`).join('\n')}
    };
}
`;

// ------------------------------------------------------------------ write / check

const outputs = [
  [join(repoRoot, 'src/Dray.Ui/wwwroot/icons/sprite.svg'), sprite],
  [join(repoRoot, 'src/Dray.Ui/Components/IconSprite.razor'), spriteRazor],
  [join(repoRoot, 'src/Dray.Core/Shell/Icons.g.cs'), cs],
];

let stale = 0;
for (const [path, content] of outputs) {
  const rel = path.slice(repoRoot.length + 1);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`  \x1b[31mSTALE\x1b[0m ${rel}`);
    stale++;
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`  \x1b[32m✎\x1b[0m ${rel}`);
}

if (check && stale) {
  console.error(`\n\x1b[31m\x1b[1m${stale} generated icon file(s) out of date.\x1b[0m Run: node build/gen-icons.mjs`);
  process.exit(1);
}
console.log(check ? '\x1b[32m✓ Icons current.\x1b[0m' : `\x1b[32m✓ ${names.length} icons generated.\x1b[0m`);
