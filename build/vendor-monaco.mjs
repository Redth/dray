#!/usr/bin/env node
// Copies the parts of monaco-editor Dray actually serves into wwwroot.
//
// Why vendor at all: the editor must work with no network. Dray opens files out of containers on
// machines that may be air-gapped, and a CDN reference would make "edit this config" depend on
// the internet being up. The macOS WebView also serves from a custom scheme, where a remote
// script is a CSP problem rather than a convenience.
//
// Why not copy the whole package: min/vs is 15 MB, and 8.9 MB of that is five language-service
// workers. Dray needs two of them. The rest — TypeScript, CSS and HTML language services — exist
// to power an IDE, and Dray is opening nginx.conf.
//
//   node build/vendor-monaco.mjs           refresh wwwroot/lib/monaco from node_modules
//   node build/vendor-monaco.mjs --check   fail if the vendored copy is stale (CI gate)

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules', 'monaco-editor');
const target = join(root, 'src', 'Dray.Ui', 'wwwroot', 'lib', 'monaco');
const manifestPath = join(target, 'vendored.json');

const check = process.argv.includes('--check');

// ---------------------------------------------------------------- what ships

// The two workers Dray has a use for. `editor.worker` is the core one — without it the editor
// falls back to running tokenisation on the UI thread and stutters on a large file. `json.worker`
// gives schema validation and completion in JSON, which is the format most often edited in a
// container. The css, html and typescript workers are 8 MB of IDE that Dray never opens.
const KEEP_WORKERS = ['editor.worker', 'json.worker'];

// Monaco ships every UI string in fourteen languages. Dray is English-only, and shipping the
// other thirteen would be a megabyte of strings nothing reads. Revisit when Dray is localised.
const KEEP_NLS = 'nls.messages.js.js';

function isDroppedWorker(name) {
  return !KEEP_WORKERS.some(keep => name.startsWith(`${keep}-`) || name === `${keep}.js`);
}

function isDroppedNls(name) {
  return name.startsWith('nls.messages.') && name.endsWith('.js.js') && name !== KEEP_NLS;
}

// ---------------------------------------------------------------- copy

function collect(dir, base = dir) {
  const files = [];

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    const rel = relative(base, full);

    if (entry.isDirectory()) {
      files.push(...collect(full, base));
      continue;
    }

    // Source maps double the size and are only useful to someone debugging Monaco itself.
    if (entry.name.endsWith('.map')) continue;
    if (isDroppedNls(entry.name)) continue;
    if (rel.startsWith('assets/') && isDroppedWorker(entry.name)) continue;

    files.push(rel);
  }

  return files.sort();
}

function build() {
  if (!existsSync(source)) {
    console.error('monaco-editor is not installed. Run `npm install` first.');
    process.exit(1);
  }

  const version = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8')).version;
  const vsSource = join(source, 'min', 'vs');
  const files = collect(vsSource);

  return { version, vsSource, files };
}

function hashOf(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 16);
}

const { version, vsSource, files } = build();

// The manifest records what a correct vendored tree looks like, so --check can tell "stale" from
// "someone edited a vendored file by hand" — both of which should fail, for different reasons.
const manifest = {
  note: 'Generated by build/vendor-monaco.mjs. Do not edit, and do not edit the files it lists.',
  version,
  workers: KEEP_WORKERS,
  locale: KEEP_NLS,
  files: Object.fromEntries(files.map(f => [f, hashOf(join(vsSource, f))])),
};

if (check) {
  const problems = [];

  if (!existsSync(manifestPath)) {
    problems.push('wwwroot/lib/monaco has never been vendored.');
  } else {
    const current = JSON.parse(readFileSync(manifestPath, 'utf8'));

    if (current.version !== version) {
      problems.push(`vendored Monaco is ${current.version}, package.json wants ${version}.`);
    }

    for (const [file, hash] of Object.entries(manifest.files)) {
      const path = join(target, 'vs', file);

      if (!existsSync(path)) problems.push(`missing: vs/${file}`);
      else if (hashOf(path) !== hash) problems.push(`modified: vs/${file}`);
    }

    for (const file of Object.keys(current.files ?? {})) {
      if (!(file in manifest.files)) problems.push(`no longer part of the build: vs/${file}`);
    }
  }

  if (problems.length > 0) {
    console.error('\x1b[31m\x1b[1m✗ Vendored Monaco is stale\x1b[0m\n');
    for (const problem of problems.slice(0, 12)) console.error(`  ${problem}`);
    if (problems.length > 12) console.error(`  …and ${problems.length - 12} more`);
    console.error('\n  Run: npm run vendor:monaco');
    process.exit(1);
  }

  console.log(`\x1b[32m\x1b[1m✓ Monaco ${version} vendored and current\x1b[0m — ${files.length} files.`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });

for (const file of files) {
  const to = join(target, 'vs', file);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(join(vsSource, file), to);
}

// The licence travels with the code. Monaco is MIT, and shipping the bytes without it would be
// both wrong and trivially avoidable.
cpSync(join(source, 'LICENSE'), join(target, 'LICENSE'));

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const bytes = files.reduce((sum, f) => sum + statSync(join(target, 'vs', f)).size, 0);
const dropped = collect(vsSource, vsSource).length;

console.log(`\x1b[32m\x1b[1m✓ Vendored Monaco ${version}\x1b[0m`);
console.log(`  ${files.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB → wwwroot/lib/monaco`);
console.log(`  workers kept: ${KEEP_WORKERS.join(', ')}`);
void dropped;
