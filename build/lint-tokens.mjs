#!/usr/bin/env node
// DESIGN.md section 11, gate 2.
//
// Fails on any raw colour literal or hardcoded font-size in hand-written UI source.
// This is the specific rule that would have prevented MAUI.Sherpa's 253 stray hex values
// in .razor files, and its purple Windows title bar sitting over a blue web accent.
//
//   node build/lint-tokens.mjs

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { repoRoot } from './color.mjs';

const SCAN = ['src'];
const EXTENSIONS = ['.css', '.razor', '.cs', '.html', '.js'];
const SKIP_DIRS = new Set(['bin', 'obj', 'node_modules', '.git', 'wwwroot/lib', 'Migrations']);

// Generated by the token pipeline — these are the one legitimate home for literal colour.
const GENERATED = [
  join('src', 'Dray.Ui', 'wwwroot', 'css', 'tokens.css'),
  join('src', 'Dray.Core', 'Theme', 'Tokens.g.cs'),
];

const RULES = [
  {
    id: 'raw-hex',
    // 3, 4, 6 or 8 digit hex, not preceded by a word char (avoids matching sha256:abc… digests)
    re: /(?<![\w&#])#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b/g,
    msg: 'raw hex colour — use a semantic token from tokens.css / DrayTokens',
  },
  {
    id: 'raw-rgb-hsl',
    re: /\b(?:rgba?|hsla?)\s*\(/g,
    msg: 'raw rgb()/hsl() colour — use a semantic token, or color-mix() over one',
  },
  {
    // The one this file missed for a while. OKLCH is how design/tokens.json authors colour, so a
    // raw oklch() in a component is not an unusual way to write a colour — it is the *same* way,
    // bypassing the generator, the gamut check and the contrast gate. lab/lch/color() are here for
    // the same reason.
    id: 'raw-modern-color',
    re: /\b(?:oklch|oklab|lch|lab|color)\s*\(/g,
    msg: 'raw oklch()/lab()/color() — author it in design/tokens.json and use the generated token',
  },
  {
    id: 'named-color',
    re: /(?<![-\w])(?:color|background|background-color|border-color|fill|stroke)\s*:\s*(?:red|green|blue|orange|yellow|purple|grey|gray|black|white|pink|cyan|magenta)\b/gi,
    msg: 'CSS named colour — use a semantic token',
  },
  {
    id: 'px-font-size',
    re: /font-size\s*:\s*\d+(?:\.\d+)?px/gi,
    msg: 'hardcoded px font-size — use var(--text-xs|sm|base|md|lg|xl)',
  },
  {
    id: 'magic-z-index',
    re: /z-index\s*:\s*(?!var\(|0\b|-1\b|auto\b|inherit\b)\S+/gi,
    msg: 'raw z-index — use var(--z-sticky|dropdown|overlay|dialog|toast|tooltip)',
  },
];

// `design-lint-ok: <reason>` suppresses a finding when it appears on the same line, or anywhere
// in the contiguous comment block immediately above it — so a justification may span lines
// without silently losing its effect.
const ALLOW = /(?:\/\/|\/\*|\*|<!--)\s*design-lint-ok\b/;
const COMMENT_LINE = /^\s*(?:\/\/|\/\*|\*|<!--|\*\/)/;

function isSuppressed(lines, index) {
  if (ALLOW.test(lines[index])) return true;

  for (let i = index - 1; i >= 0; i--) {
    const line = lines[i];
    if (ALLOW.test(line)) return true;
    if (!COMMENT_LINE.test(line)) return false;
  }
  return false;
}

function* walk(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    const full = join(dir, name);
    const rel = relative(repoRoot, full);
    if (SKIP_DIRS.has(name) || [...SKIP_DIRS].some((d) => rel.split(sep).join('/').includes(d))) continue;
    const st = statSync(full);
    if (st.isDirectory()) yield* walk(full);
    else if (EXTENSIONS.some((e) => name.endsWith(e))) yield full;
  }
}

const findings = [];
let scanned = 0;

for (const root of SCAN) {
  for (const file of walk(join(repoRoot, root))) {
    const rel = relative(repoRoot, file);
    if (GENERATED.includes(rel)) continue;
    scanned++;

    const lines = readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, i) => {
      if (isSuppressed(lines, i)) return;
      for (const rule of RULES) {
        rule.re.lastIndex = 0;
        let m;
        while ((m = rule.re.exec(line)) !== null) {
          findings.push({ file: rel, line: i + 1, col: m.index + 1, rule, match: m[0].trim() });
        }
      }
    });
  }
}

if (findings.length) {
  console.error(`\x1b[31m\x1b[1mToken lint failed — ${findings.length} finding(s) in ${scanned} file(s):\x1b[0m\n`);
  for (const f of findings) {
    console.error(`  \x1b[1m${f.file}:${f.line}:${f.col}\x1b[0m`);
    console.error(`    \x1b[31m${f.match}\x1b[0m  — ${f.rule.msg}  \x1b[2m[${f.rule.id}]\x1b[0m`);
  }
  console.error(
    '\nColour and type live in design/tokens.json and nowhere else.\n' +
      'If a literal is genuinely unavoidable, annotate the line with `design-lint-ok: <reason>`.'
  );
  process.exit(1);
}

console.log(`\x1b[32m\x1b[1m✓ Token lint clean\x1b[0m — ${scanned} file(s), ${RULES.length} rules.`);
