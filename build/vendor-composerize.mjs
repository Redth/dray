#!/usr/bin/env node
// Builds composerize into wwwroot, for turning a `docker run` line into a compose service.
//
// The parser is the problem: `docker run` takes well over a hundred flags, each with its own value
// grammar, and composerize is the maintained MIT library that maps them onto the compose spec. It
// is what Dockge uses for the same feature. Dray only hands it a string and takes back YAML.
//
// The package ships a UMD build with its source map inlined (1.9 MB). esbuild rewraps it as one
// minified ES module the browser can import, without the map — about 280 KB, loaded only when the
// New stack dialog is asked to convert something.
//
//   node build/vendor-composerize.mjs           rebuild wwwroot/lib/composerize
//   node build/vendor-composerize.mjs --check   fail if the vendored copy is stale (CI gate)

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');
const target = join(root, 'src', 'Dray.Ui', 'wwwroot', 'lib', 'composerize');
const manifestPath = join(target, 'vendored.json');
const check = process.argv.includes('--check');

if (!existsSync(join(modules, 'composerize')) || !existsSync(join(modules, 'esbuild'))) {
  console.error('composerize is not installed. Run `npm install` first.');
  process.exit(1);
}

const version = JSON.parse(readFileSync(join(modules, 'composerize', 'package.json'), 'utf8')).version;
const hashOf = (bytes) => createHash('sha256').update(bytes).digest('hex').slice(0, 16);

const result = await build({
  entryPoints: [join(modules, 'composerize', 'dist', 'composerize.js')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  logLevel: 'error',
  absWorkingDir: root,
});

const bytes = Buffer.from(result.outputFiles[0].contents);
const manifest = {
  note: 'Generated by build/vendor-composerize.mjs. Do not edit, and do not edit the files it lists.',
  version,
  files: { 'composerize.js': hashOf(bytes) },
};

if (check) {
  const problems = [];

  if (!existsSync(manifestPath)) problems.push('wwwroot/lib/composerize has never been vendored.');
  else {
    const current = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (current.version !== version) problems.push(`vendored composerize is ${current.version}, package.json wants ${version}.`);

    const path = join(target, 'composerize.js');
    if (!existsSync(path)) problems.push('missing: composerize.js');
    else if (hashOf(readFileSync(path)) !== manifest.files['composerize.js']) problems.push('stale or modified: composerize.js');
  }

  if (problems.length > 0) {
    console.error('\x1b[31m\x1b[1m✗ Vendored composerize is stale\x1b[0m\n');
    for (const problem of problems) console.error(`  ${problem}`);
    console.error('\n  Run: npm run vendor:composerize');
    process.exit(1);
  }

  console.log(`\x1b[32m\x1b[1m✓ composerize ${version} vendored and current\x1b[0m`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
writeFileSync(join(target, 'composerize.js'), bytes);

// MIT. The package carries its licence in package.json and the README rather than a LICENSE file.
writeFileSync(join(target, 'LICENSE.txt'),
  'composerize — https://github.com/composerize/composerize — MIT License\n'
  + 'Copyright (c) the composerize contributors.\n');

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`\x1b[32m\x1b[1m✓ Vendored composerize ${version}\x1b[0m — ${(bytes.length / 1024).toFixed(0)} KB → wwwroot/lib/composerize`);
