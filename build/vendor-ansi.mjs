#!/usr/bin/env node
// Copies ansi_up into wwwroot, for the same reason as the rest: the app must work with the network
// unplugged, and a strict WebView CSP would block a CDN anyway.
//
// One file. Container output is full of ANSI escapes — every program that colours its own logs
// emits them — and without this they render as literal `[0;32m` noise in the middle of every line.
// Turning them into spans is a small, well-understood job with a decade-old MIT library, and is not
// a thing to hand-roll: the escape grammar has 8-bit and 24-bit colour, and a parser that gets it
// slightly wrong corrupts the text rather than the colour.
//
//   node build/vendor-ansi.mjs           refresh wwwroot/lib/ansi from node_modules
//   node build/vendor-ansi.mjs --check   fail if the vendored copy is stale (CI gate)

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'Dray.Ui', 'wwwroot', 'lib', 'ansi');
const manifestPath = join(target, 'vendored.json');

const check = process.argv.includes('--check');

const FILES = [
  { from: ['ansi_up', 'ansi_up.js'], to: 'ansi_up.js' },
];

const LICENCES = [
  { from: ['ansi_up', 'LICENSE'], to: 'LICENSE' },
];

function pkgPath(...parts) {
  return join(root, 'node_modules', ...parts);
}

function version() {
  return JSON.parse(readFileSync(pkgPath('ansi_up', 'package.json'), 'utf8')).version;
}

function hashOf(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 16);
}

if (!existsSync(pkgPath('ansi_up'))) {
  console.error('ansi_up is not installed. Run `npm install` first.');
  process.exit(1);
}

const manifest = {
  note: 'Generated by build/vendor-ansi.mjs. Do not edit, and do not edit the files it lists.',
  version: version(),
  files: Object.fromEntries(FILES.map(f => [f.to, hashOf(pkgPath(...f.from))])),
};

if (check) {
  const problems = [];

  if (!existsSync(manifestPath)) {
    problems.push('wwwroot/lib/ansi has never been vendored.');
  } else {
    const current = JSON.parse(readFileSync(manifestPath, 'utf8'));

    if (current.version !== manifest.version) {
      problems.push(`vendored ansi_up is ${current.version}, package.json wants ${manifest.version}.`);
    }

    for (const [file, hash] of Object.entries(manifest.files)) {
      const path = join(target, file);

      if (!existsSync(path)) problems.push(`missing: ${file}`);
      else if (hashOf(path) !== hash) problems.push(`modified: ${file}`);
    }
  }

  if (problems.length > 0) {
    console.error('\x1b[31m\x1b[1m✗ Vendored ansi_up is stale\x1b[0m\n');
    for (const problem of problems) console.error(`  ${problem}`);
    console.error('\n  Run: npm run vendor:tabulator');
    process.exit(1);
  }

  console.log(`\x1b[32m\x1b[1m✓ ansi_up ${manifest.version} vendored and current\x1b[0m`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

for (const file of [...FILES, ...LICENCES]) {
  cpSync(pkgPath(...file.from), join(target, file.to));
}

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const bytes = FILES.reduce((sum, f) => sum + statSync(join(target, f.to)).size, 0);

console.log(`\x1b[32m\x1b[1m✓ Vendored ansi_up ${manifest.version}\x1b[0m`);
console.log(`  ${FILES.length} files, ${(bytes / 1024).toFixed(0)} KB → wwwroot/lib/ansi`);
