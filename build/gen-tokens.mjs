#!/usr/bin/env node
// Generates every downstream artefact from design/tokens.json:
//
//   src/Dray.Ui/wwwroot/css/tokens.css   the WebView's custom properties
//   src/Dray.Core/Theme/Tokens.g.cs      the same values for native chrome (NSColor / WinUI / GTK)
//   DESIGN.md                            the palette tables, between generated markers
//
// One source means NSColor and CSS cannot disagree — the failure DESIGN.md section 11 exists to
// prevent, and the one visible in MAUI.Sherpa's purple Windows title bar over a blue web accent.
//
//   node build/gen-tokens.mjs            write
//   node build/gen-tokens.mjs --check    fail if anything is stale (CI)

import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { loadTokens, resolveTheme, toCss, toHex, contrastRatio, oklchToSrgb, repoRoot, themes } from './color.mjs';

const check = process.argv.includes('--check');
const tokens = loadTokens();
const resolved = Object.fromEntries(themes.map((t) => [t, resolveTheme(tokens, t)]));

const BANNER = `Generated by build/gen-tokens.mjs from design/tokens.json. Do not edit.`;

// ---------------------------------------------------------------- tokens.css

function cssBlock(theme, indent = '  ') {
  const decls = Object.entries(resolved[theme]).map(([role, oklch]) => ({
    decl: `--${role}: ${toCss(oklch)};`,
    hex: toHex(oklch),
  }));
  const width = Math.max(...decls.map((d) => d.decl.length)) + 2;
  const colors = decls.map((d) => `${indent}${d.decl.padEnd(width)}/* ${d.hex} */`);

  // Effects carry alpha and are not palette entries, so they are emitted verbatim.
  const effects = Object.entries(tokens.effects?.[theme] ?? {})
    .filter(([k]) => !k.startsWith('$'))
    .map(([k, v]) => `${indent}--${k}: ${v};`);

  return effects.length ? [...colors, '', ...effects].join('\n') : colors.join('\n');
}

function scaleBlock() {
  const s = tokens.scale;
  const out = [];
  out.push('  /* space */');
  for (const [k, v] of Object.entries(s.space)) out.push(`  --${k}: ${v};`);
  out.push('', '  /* radius */');
  for (const [k, v] of Object.entries(s.radius)) out.push(`  --${k}: ${v};`);
  out.push('', '  /* type — fixed rem scale, ratio 1.125. No clamp() in product UI. */');
  for (const [k, v] of Object.entries(s.text)) {
    out.push(`  --text-${k}: ${v.size};`);
    out.push(`  --text-${k}-weight: ${v.weight};`);
    out.push(`  --text-${k}-lh: ${v.lh};`);
  }
  out.push('', '  /* z-index — a named scale, never an arbitrary number */');
  for (const [k, v] of Object.entries(s.z)) out.push(`  --z-${k}: ${v};`);
  out.push('', '  /* motion */');
  for (const [k, v] of Object.entries(s.motion)) out.push(`  --motion-${k}: ${v};`);
  out.push('', '  /* density — default comfortable; .density-compact swaps these */');
  for (const [k, v] of Object.entries(s.density.comfortable)) out.push(`  --${k}: ${v};`);
  return out.join('\n');
}

const css = `/* ${BANNER} */

:root {
  color-scheme: light;

${cssBlock('light')}

${scaleBlock()}
}

.density-compact {
${Object.entries(tokens.scale.density.compact).map(([k, v]) => `  --${k}: ${v};`).join('\n')}
}

/* Default "system" appearance stamps nothing on the root, so prefers-color-scheme is
   the only signal. Guarded so an explicit light choice still beats a dark OS. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;

${cssBlock('dark', '    ')}
  }
}

/* Explicit choice wins in both directions. */
:root[data-theme="dark"] {
  color-scheme: dark;

${cssBlock('dark')}
}

:root[data-theme="light"] {
  color-scheme: light;

${cssBlock('light')}
}

/* The native window paints the ground; the WebView is transparent over it.
   These are the fallbacks used before the host pushes the platform colour
   (DESIGN.md section 9.1) and whenever no host is present. */
html, body {
  background: var(--bg);
  color: var(--ink);
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --motion-fast: 1ms;
    --motion-base: 1ms;
    --motion-slow: 1ms;
  }
}
`;

// ---------------------------------------------------------------- Tokens.g.cs

function csBlock(theme) {
  return Object.entries(resolved[theme])
    .map(([role, oklch]) => {
      const [r, g, b] = oklchToSrgb(oklch).map((c) => Math.round(Math.min(1, Math.max(0, c)) * 255));
      return `        [DrayColor.${pascal(role)}] = new(${r}, ${g}, ${b}),`;
    })
    .join('\n');
}

const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const roleNames = Object.keys(resolved.light);

const cs = `// ${BANNER}
#nullable enable

namespace Dray.Core.Theme;

/// <summary>Every semantic colour role in Dray. Native chrome and CSS resolve the same values.</summary>
public enum DrayColor
{
${roleNames.map((r) => `    ${pascal(r)},`).join('\n')}
}

/// <summary>An sRGB colour, 0-255 per channel.</summary>
public readonly record struct DrayRgb(byte R, byte G, byte B)
{
    public string ToHex() => $"#{R:x2}{G:x2}{B:x2}";
}

public enum DrayTheme { Light, Dark }

/// <summary>
/// Generated palette. Platform heads build their native colour type from these
/// (NSColor on macOS, Windows.UI.Color on WinUI, Gdk.RGBA on GTK) so the native
/// chrome and the WebView content can never drift apart.
/// </summary>
public static class DrayTokens
{
    public static DrayRgb Get(DrayTheme theme, DrayColor color) =>
        theme == DrayTheme.Dark ? Dark[color] : Light[color];

    public static readonly IReadOnlyDictionary<DrayColor, DrayRgb> Light = new Dictionary<DrayColor, DrayRgb>
    {
${csBlock('light')}
    };

    public static readonly IReadOnlyDictionary<DrayColor, DrayRgb> Dark = new Dictionary<DrayColor, DrayRgb>
    {
${csBlock('dark')}
    };
}
`;

// ---------------------------------------------------------------- DESIGN.md tables

function mdTable(theme) {
  const rows = [`| Token | OKLCH | Hex | Contrast |`, `|---|---|---|---|`];
  const bg = resolved[theme].bg;
  for (const [role, oklch] of Object.entries(resolved[theme])) {
    const ratio = role === 'bg' ? '—' : `${contrastRatio(oklch, bg).toFixed(2)}:1 vs bg`;
    rows.push(`| \`--${role}\` | \`${toCss(oklch)}\` | \`${toHex(oklch)}\` | ${ratio} |`);
  }
  return rows.join('\n');
}

function spliceMarkers(text, name, body) {
  const start = `<!-- generated:${name}:start -->`;
  const end = `<!-- generated:${name}:end -->`;
  const i = text.indexOf(start);
  const j = text.indexOf(end);
  if (i === -1 || j === -1) throw new Error(`DESIGN.md is missing the ${start} / ${end} markers`);
  return text.slice(0, i + start.length) + '\n' + body + '\n' + text.slice(j);
}

const designPath = join(repoRoot, 'DESIGN.md');
let design = readFileSync(designPath, 'utf8');
design = spliceMarkers(design, 'palette-light', mdTable('light'));
design = spliceMarkers(design, 'palette-dark', mdTable('dark'));

// ---------------------------------------------------------------- write / check

const outputs = [
  [join(repoRoot, 'src/Dray.Ui/wwwroot/css/tokens.css'), css],
  [join(repoRoot, 'src/Dray.Core/Theme/Tokens.g.cs'), cs],
  [designPath, design],
];

let stale = 0;
for (const [path, content] of outputs) {
  const rel = path.slice(repoRoot.length + 1);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) {
    if (!check) console.log(`  = ${rel}`);
    continue;
  }
  if (check) {
    console.error(`  \x1b[31mSTALE\x1b[0m ${rel}`);
    stale++;
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`  \x1b[32m✎\x1b[0m ${rel}`);
}

if (check && stale) {
  console.error(`\n\x1b[31m\x1b[1m${stale} generated file(s) are out of date.\x1b[0m Run: node build/gen-tokens.mjs`);
  process.exit(1);
}

console.log(check ? '\n\x1b[32m✓ Generated files are current.\x1b[0m' : '\n\x1b[32m✓ Tokens generated.\x1b[0m');
